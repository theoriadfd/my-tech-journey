# Мой первый скрипт на Python

# print() выводит текст на экран
print("Привет, мир!")

# input() спрашивает что-то у пользователя и возвращает ответ как строку
name = input("Как тебя зовут? ")

# f-строка подставляет значение переменной в текст
print(f"Рад знакомству, {name}! Добро пожаловать в Python.")
